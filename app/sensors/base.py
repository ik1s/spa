"""Базовые классы для всех датчиков.

Чтобы добавить новый датчик, нужно сделать три вещи:
1. Написать класс-наследник Sensor с методом read() (пример: dht11.py).
2. Зарегистрировать его в словаре SENSOR_TYPES в sensors/__init__.py.
3. Описать его в config.yaml в списке sensors.
"""


class SensorError(Exception):
    """Ошибка чтения датчика (обрыв провода, неверная контрольная сумма и т.п.).

    Приложение ловит именно это исключение: при ошибке оно помечает датчик как
    неисправный в /health и метриках, но не падает и продолжает опрос.
    """


class Sensor:
    # Имя датчика из config.yaml. Попадает в метки метрик (sensor="dht11_1").
    name: str

    def read(self) -> dict:
        """Прочитать датчик.

        Возвращает словарь вида {"temperature_celsius": 24.9, "humidity_percent": 50.1}.
        При неудаче нужно бросить SensorError.
        """
        raise NotImplementedError
